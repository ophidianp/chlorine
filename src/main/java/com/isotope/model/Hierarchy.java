package com.isotope.model;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.Reader;
import java.io.Writer;
import java.util.Collection;
import java.util.HashMap;
import java.util.Map;
import java.util.TreeMap;

/**
 * Who extends / implements whom in one game version, with nothing else.
 *
 * <p>Isotope ships one of these per supported version (a few hundred KB of text) so it
 * can answer "which parent class declared this method back in 26.1.2?" while running
 * on 26.3, where the 26.1.2 jar is not available. Format: one class per line,
 * {@code name[!] super iface1 iface2 ...} where {@code !} marks an interface and
 * {@code -} means "java/lang/Object".
 */
public final class Hierarchy {
	public record Node(String superName, String[] interfaces, boolean isInterface) { }

	private final Map<String, Node> nodes = new HashMap<>();

	public Node get(String name) {
		return nodes.get(name);
	}

	public boolean contains(String name) {
		return nodes.containsKey(name);
	}

	public int size() {
		return nodes.size();
	}

	public void put(String name, Node node) {
		nodes.put(name, node);
	}

	public static Hierarchy of(Collection<ClassInfo> classes) {
		Hierarchy h = new Hierarchy();
		for (ClassInfo c : classes) h.nodes.put(c.name, new Node(c.superName, c.interfaces, c.isInterface()));
		return h;
	}

	public static Hierarchy read(Reader in) throws IOException {
		Hierarchy h = new Hierarchy();
		BufferedReader r = new BufferedReader(in);
		String line;

		while ((line = r.readLine()) != null) {
			if (line.isEmpty() || line.charAt(0) == '#') continue;
			String[] p = line.split(" ");
			boolean itf = p[0].endsWith("!");
			String name = itf ? p[0].substring(0, p[0].length() - 1) : p[0];
			String sup = p.length < 2 || p[1].equals("-") ? "java/lang/Object" : p[1];
			String[] ifaces = new String[Math.max(0, p.length - 2)];
			if (ifaces.length > 0) System.arraycopy(p, 2, ifaces, 0, ifaces.length);
			h.nodes.put(name, new Node(sup, ifaces, itf));
		}

		return h;
	}

	public void write(Writer w, String version) throws IOException {
		w.write("# isotope hierarchy for Minecraft " + version + " (generated by DiffGen; do not edit)\n");

		for (Map.Entry<String, Node> e : new TreeMap<>(nodes).entrySet()) {
			Node n = e.getValue();
			StringBuilder sb = new StringBuilder(e.getKey());
			if (n.isInterface()) sb.append('!');
			sb.append(' ').append(n.superName() == null || n.superName().equals("java/lang/Object") ? "-" : n.superName());
			for (String i : n.interfaces()) sb.append(' ').append(i);
			w.write(sb.append('\n').toString());
		}
	}
}
