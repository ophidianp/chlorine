package com.isotope.model;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.Reader;
import java.io.Writer;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * One hop of redirects, e.g. "26.2 to 26.3": everything that kept its meaning but
 * changed its name or address between two game versions.
 *
 * <p>File format (one rule per line, space separated, {@code #} starts a comment):
 * <pre>
 * isotope-redirects 1
 * from 26.2
 * to 26.3
 * c &lt;oldClass&gt; &lt;newClass&gt;                         a class moved or was renamed
 * m &lt;owner&gt; &lt;name&gt; &lt;desc&gt; &lt;newName&gt; [newDesc] [cast] [private]  a method was renamed / its signature changed compatibly
 * f &lt;owner&gt; &lt;name&gt; &lt;desc&gt; &lt;newName&gt; [private]                a field was renamed
 * s m|f &lt;owner&gt; &lt;name&gt; &lt;desc&gt; &lt;reason...&gt;          a removed member; uses get a default value (hand-written only)
 * </pre>
 * {@code owner}, {@code name} and {@code desc} are always written in the OLD version's
 * names. {@code newDesc} is written in the NEW version's names. Tables are generated by
 * {@code com.isotope.tools.DiffGen}; hand-written rules can be appended to the same file.
 */
public final class RedirectTable {
	public static final String HEADER = "isotope-redirects 1";

	/**
	 * @param owner   class that declares the member, old name
	 * @param name    old member name
	 * @param desc    old descriptor (old class names)
	 * @param newName new member name
	 * @param newDesc new descriptor in NEW class names, or null if only class renames apply
	 * @param cast    true if the new method returns a wider type and callers need a checkcast
	 * @param priv    true if the member is private: the rule then only applies to the declaring
	 *                class itself (and mixins into it), never to subclasses
	 */
	public record Member(String owner, String name, String desc, String newName, String newDesc, boolean cast, boolean priv) {
		/** A "blocker": the member keeps its name; the rule only exists to stop hierarchy lookups. */
		public boolean isIdentity() {
			return newDesc == null && name.equals(newName);
		}
	}

	/**
	 * A removed game member that calls are allowed to "succeed" against: the call is replaced
	 * with a default value (null, 0, false, or nothing). Only for members whose whole system the
	 * game dropped, so nothing in the game would ever read the value anyway. Hand-written only.
	 *
	 * @param field  true for a field, false for a method
	 * @param reason shown in the report
	 */
	public record Stub(boolean field, String owner, String name, String desc, String reason) { }

	private final Map<String, Stub> stubs = new LinkedHashMap<>();

	public void addStub(Stub stub) {
		stubs.put((stub.field() ? "f " : "m ") + stub.owner() + ' ' + stub.name() + ' ' + stub.desc(), stub);
	}

	/** Stub declared exactly on {@code owner}, or null. */
	public Stub stub(boolean field, String owner, String name, String desc) {
		return stubs.get((field ? "f " : "m ") + owner + ' ' + name + ' ' + desc);
	}

	public boolean hasStubs() {
		return !stubs.isEmpty();
	}

	public String from = "?";
	public String to = "?";
	public final Map<String, String> classes = new LinkedHashMap<>();
	private final Map<String, Member> methods = new LinkedHashMap<>();
	private final Map<String, Member> fields = new LinkedHashMap<>();
	private final Map<String, List<Member>> methodsByOwnerName = new LinkedHashMap<>();
	private final Map<String, List<Member>> fieldsByOwnerName = new LinkedHashMap<>();

	public void addMethod(Member m) {
		methods.put(m.owner() + ' ' + m.name() + ' ' + m.desc(), m);
		methodsByOwnerName.computeIfAbsent(m.owner() + ' ' + m.name(), k -> new ArrayList<>()).add(m);
	}

	public void addField(Member f) {
		fields.put(f.owner() + ' ' + f.name() + ' ' + f.desc(), f);
		fieldsByOwnerName.computeIfAbsent(f.owner() + ' ' + f.name(), k -> new ArrayList<>()).add(f);
	}

	/** Rule for a method declared exactly on {@code owner}, or null. */
	public Member method(String owner, String name, String desc) {
		return methods.get(owner + ' ' + name + ' ' + desc);
	}

	public Member field(String owner, String name, String desc) {
		return fields.get(owner + ' ' + name + ' ' + desc);
	}

	/** All method rules on {@code owner} with this name, any descriptor (used for mixin strings without one). */
	public List<Member> methodsNamed(String owner, String name) {
		return methodsByOwnerName.getOrDefault(owner + ' ' + name, Collections.emptyList());
	}

	public List<Member> fieldsNamed(String owner, String name) {
		return fieldsByOwnerName.getOrDefault(owner + ' ' + name, Collections.emptyList());
	}

	public Iterable<Member> allMethods() {
		return methods.values();
	}

	public Iterable<Member> allFields() {
		return fields.values();
	}

	public int methodCount() {
		return methods.size();
	}

	public int fieldCount() {
		return fields.size();
	}

	public boolean isEmpty() {
		return classes.isEmpty() && methods.isEmpty() && fields.isEmpty();
	}

	/** Maps an old class name to its new name; inner classes follow a moved outer class. */
	public String mapClass(String oldName) {
		String direct = classes.get(oldName);
		if (direct != null) return direct;

		// Outer$Inner follows Outer unless it has its own rule.
		int dollar = oldName.lastIndexOf('$');

		while (dollar > 0) {
			String outer = classes.get(oldName.substring(0, dollar));
			if (outer != null) return outer + oldName.substring(dollar);
			dollar = oldName.lastIndexOf('$', dollar - 1);
		}

		return oldName;
	}

	public static RedirectTable read(Reader in) throws IOException {
		RedirectTable t = new RedirectTable();
		t.readInto(in);
		return t;
	}

	/**
	 * Adds the rules from another file in the same format to this table. Used for the
	 * hand-written {@code .manual} file that sits next to each generated table.
	 */
	public void readInto(Reader in) throws IOException {
		RedirectTable t = this;
		BufferedReader r = new BufferedReader(in);
		String line = r.readLine();
		if (line == null || !line.trim().equals(HEADER)) throw new IOException("Not an Isotope redirect table (bad header)");
		int lineNo = 1;

		while ((line = r.readLine()) != null) {
			lineNo++;
			int hash = line.indexOf('#');
			if (hash >= 0) line = line.substring(0, hash);
			line = line.trim();
			if (line.isEmpty()) continue;
			String[] p = line.split("\\s+");

			try {
				switch (p[0]) {
				case "from" -> t.from = p[1];
				case "to" -> t.to = p[1];
				case "c" -> t.classes.put(p[1], p[2]);
				case "m" -> {
					String newDesc = null;
					boolean cast = false;
					boolean priv = false;

					for (int i = 5; i < p.length; i++) {
						if (p[i].equals("cast")) cast = true;
						else if (p[i].equals("private")) priv = true;
						else newDesc = p[i];
					}

					t.addMethod(new Member(p[1], p[2], p[3], p[4], newDesc, cast, priv));
				}
				case "f" -> t.addField(new Member(p[1], p[2], p[3], p[4], null, false, p.length > 5 && p[5].equals("private")));
				case "s" -> {
					// s m|f <owner> <name> <desc> <reason ...>
					if (!p[1].equals("m") && !p[1].equals("f")) throw new IOException("line " + lineNo + ": stub kind must be m or f");
					String reason = p.length > 5 ? String.join(" ", java.util.Arrays.copyOfRange(p, 5, p.length)) : "removed from the game";
					t.addStub(new Stub(p[1].equals("f"), p[2], p[3], p[4], reason));
				}
				default -> throw new IOException("unknown rule kind '" + p[0] + "'");
				}
			} catch (ArrayIndexOutOfBoundsException e) {
				throw new IOException("line " + lineNo + ": too few columns: " + line);
			}
		}
	}

	public void write(Writer w, List<String> headerComments) throws IOException {
		w.write(HEADER + "\n");
		for (String c : headerComments) w.write("# " + c + "\n");
		w.write("from " + from + "\n");
		w.write("to " + to + "\n");

		for (Map.Entry<String, String> e : classes.entrySet()) {
			w.write("c " + e.getKey() + " " + e.getValue() + "\n");
		}

		for (Member m : methods.values()) {
			w.write("m " + m.owner() + " " + m.name() + " " + m.desc() + " " + m.newName()
					+ (m.newDesc() != null ? " " + m.newDesc() : "") + (m.cast() ? " cast" : "") + (m.priv() ? " private" : "") + "\n");
		}

		for (Member f : fields.values()) {
			w.write("f " + f.owner() + " " + f.name() + " " + f.desc() + " " + f.newName() + (f.priv() ? " private" : "") + "\n");
		}

		for (Stub st : stubs.values()) {
			w.write("s " + (st.field() ? "f " : "m ") + st.owner() + " " + st.name() + " " + st.desc() + " " + st.reason() + "\n");
		}
	}
}
