	/** Per-class code summary, computed on demand for classes that actually lost a member. */
	private static final class Bodies {
		/** methodKey (old names) -> instruction tokens, class names passed through the mapper. */
		final Map<String, List<String>> tokens = new HashMap<>();
		/** static field name -> the instructions in {@code <clinit>} that compute its value. */
		final Map<String, String> staticInit = new HashMap<>();
		/** field name -> "name+desc" (mapped) of every method of this class that reads or writes it. */
		final Map<String, Set<String>> fieldUsers = new HashMap<>();

		static boolean isDistinctive(String init) {
			// Needs a string constant to be worth trusting ("stone", "entity.pig.ambient", ...).
			// The field's own name does not count: for a plain enum constant that is all there is,
			// and then two renamed constants are indistinguishable.
			return init.replace("ldc \"<self>\"", "").contains("ldc \"");
		}

		static Bodies read(byte[] classBytes, UnaryOperator<String> mapper) {
			Bodies out = new Bodies();
			String[] self = new String[1];

			new ClassReader(classBytes).accept(new ClassVisitor(Opcodes.ASM9) {
				@Override
				public void visit(int version, int access, String name, String signature, String superName, String[] interfaces) {
					self[0] = name;
				}

				@Override
				public MethodVisitor visitMethod(int access, String name, String descriptor, String signature, String[] exceptions) {
					List<String> list = new ArrayList<>();
					out.tokens.put(name + descriptor, list);
					boolean clinit = name.equals("<clinit>");
					String userKey = name + mapDesc(descriptor, mapper);
					StringBuilder segment = new StringBuilder();

					return new MethodVisitor(Opcodes.ASM9) {
						private void add(String t) {
							list.add(t);
							if (clinit) segment.append(t).append(';');
						}

						@Override
						public void visitInsn(int opcode) {
							add("i" + opcode);
						}

						@Override
						public void visitIntInsn(int opcode, int operand) {
							add("n" + opcode + ":" + operand);
						}

						@Override
						public void visitVarInsn(int opcode, int varIndex) {
							add("v" + opcode); // slot numbers shift whenever a local is added; ignore them
						}

						@Override
						public void visitTypeInsn(int opcode, String type) {
							add("t" + opcode + " " + mapType(type, mapper));
						}

						@Override
						public void visitFieldInsn(int opcode, String owner, String name, String descriptor) {
							if (owner.equals(self[0])) {
								out.fieldUsers.computeIfAbsent(name, k -> new HashSet<>()).add(userKey);

								if (clinit && opcode == Opcodes.PUTSTATIC) {
									// Everything since the previous PUTSTATIC built this field's value.
									// The field's own name is left out so a pure rename compares equal.
									out.staticInit.put(name, segment.toString().replace("\"" + name + "\"", "\"<self>\""));
									segment.setLength(0);
									list.add("f" + opcode + " " + mapType(owner, mapper) + "." + name);
									return;
								}
							}

							add("f" + opcode + " " + mapType(owner, mapper) + "." + name + ":" + mapDesc(descriptor, mapper));
						}

						@Override
						public void visitMethodInsn(int opcode, String owner, String name, String descriptor, boolean isInterface) {
							add("m" + opcode + " " + mapType(owner, mapper) + "." + name + mapDesc(descriptor, mapper));
						}

						@Override
						public void visitInvokeDynamicInsn(String name, String descriptor, Handle bootstrapMethodHandle, Object... bootstrapMethodArguments) {
							add("d " + name + mapDesc(descriptor, mapper));
						}

						@Override
						public void visitJumpInsn(int opcode, Label label) {
							add("j" + opcode);
						}

						@Override
						public void visitLdcInsn(Object value) {
							if (value instanceof String s) add("ldc \"" + s + "\"");
							else if (value instanceof Type t) add("ldc " + mapDesc(t.getDescriptor(), mapper));
							else add("ldc " + value);
						}

						@Override
						public void visitIincInsn(int varIndex, int increment) {
							add("inc" + increment);
						}

						@Override
						public void visitTableSwitchInsn(int min, int max, Label dflt, Label... labels) {
							add("ts" + (max - min));
						}

						@Override
						public void visitLookupSwitchInsn(Label dflt, int[] keys, Label[] labels) {
							add("ls" + keys.length);
						}

						@Override
						public void visitMultiANewArrayInsn(String descriptor, int numDimensions) {
							add("ma " + mapDesc(descriptor, mapper));
						}
					};
				}
			}, ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);

			return out;
		}
	}

	/** -1 if neither has a body, else 0..1 (Dice coefficient over instruction multisets). */
	private static double bodySim(List<String> x, List<String> y) {
		boolean ex = x == null || x.isEmpty();
		boolean ey = y == null || y.isEmpty();
		if (ex && ey) return -1;
		if (ex || ey) return 0;
		Map<String, int[]> counts = new HashMap<>();
		for (String t : x) counts.computeIfAbsent(t, k -> new int[2])[0]++;
		for (String t : y) counts.computeIfAbsent(t, k -> new int[2])[1]++;
		int common = 0;
		for (int[] c : counts.values()) common += Math.min(c[0], c[1]);
		return 2.0 * common / (x.size() + y.size());
	}

	private static double dice(Set<String> x, Set<String> y) {
		if (x.isEmpty() && y.isEmpty()) return 0;
		int common = 0;
		for (String s : x) if (y.contains(s)) common++;
		return 2.0 * common / (x.size() + y.size());
	}

	// ---------------------------------------------------------------- helpers

	static String mapType(String internalNameOrArray, UnaryOperator<String> mapper) {
		if (internalNameOrArray.startsWith("[")) return mapDesc(internalNameOrArray, mapper);
		return mapper.apply(internalNameOrArray);
	}

	/** Rewrites every {@code Lsome/Class;} inside a descriptor through {@code mapper}. */
	static String mapDesc(String desc, UnaryOperator<String> mapper) {
		if (desc.indexOf('L') < 0) return desc;
		StringBuilder sb = new StringBuilder(desc.length() + 16);
		int i = 0;

		while (i < desc.length()) {
			char ch = desc.charAt(i);

			if (ch == 'L') {
				int semi = desc.indexOf(';', i);
				sb.append('L').append(mapper.apply(desc.substring(i + 1, semi))).append(';');
				i = semi + 1;
			} else {
				sb.append(ch);
				i++;
			}
		}

		return sb.toString();
	}

	private static boolean isSynthetic(int access) {
		return (access & Opcodes.ACC_SYNTHETIC) != 0;
	}

	private static boolean isPrivate(Integer access) {
		return access != null && (access & Opcodes.ACC_PRIVATE) != 0;
	}

	private static boolean isStatic(Integer access) {
		return access != null && (access & Opcodes.ACC_STATIC) != 0;
	}

	/** Foo$1, Foo$1Local: compiler-numbered classes that no mod can name reliably. */
	private static boolean isAnonymous(String name) {
		int i = name.indexOf('$');

		while (i >= 0 && i + 1 < name.length()) {
			if (Character.isDigit(name.charAt(i + 1))) return true;
			i = name.indexOf('$', i + 1);
		}

		return false;
	}

	private static String simpleName(String name) {
		return name.substring(name.lastIndexOf('/') + 1);
	}

	private static int count(String s, char c) {
		int n = 0;
		for (int i = 0; i < s.length(); i++) if (s.charAt(i) == c) n++;
		return n;
	}

	private static final class Stats {
		int removedClasses, addedClasses, resolvedClasses;
		int removedMethods, renamedMethods, resignedMethods;
		int removedFields, renamedFields, unresolvedFields;
		int unresolvedMethods;
		List<String> unresolvedClassNames = new ArrayList<>();
		final Map<String, Integer> unresolvedByPackage = new LinkedHashMap<>();
		final Set<String> sampleUnresolved = new TreeSet<>();

		void unresolvedMethod(String owner, String name, String desc) {
			unresolvedMethods++;
			if (sampleUnresolved.size() < 20000) sampleUnresolved.add(owner + "." + name + desc);
		}

		String summary(Jar a, Jar b) {
			return a.classes.size() + " -> " + b.classes.size() + " classes; "
					+ "missing classes " + removedClasses + " (redirected " + resolvedClasses + "), "
					+ "missing methods " + removedMethods + " (renamed " + renamedMethods + ", re-signed " + resignedMethods + ", unresolved " + unresolvedMethods + "), "
					+ "missing fields " + removedFields + " (renamed " + renamedFields + ", unresolved " + unresolvedFields + ")";
		}
	}
